import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsNotEmpty, IsString, IsUUID, IsNumberString, IsOptional } from 'class-validator';
import { IsStellarPublicKey } from './decorators/is-stellar-public-key.decorator';

export class SendUsdcDto {
  @ApiProperty({
    description: 'Unique UUID transfer identifier from the transfer-engine',
    example: 'a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d',
  })
  @IsUUID()
  @IsNotEmpty()
  transferId: string;

  @ApiProperty({
    description: 'The 56-character target Stellar public key address',
    example: 'GBBD47IF6LWK7P7TZS2ADQDPTO2DMTM26IE6XYVJ65P3ENW6CIH2WCNR',
  })
  @IsStellarPublicKey()
  @IsNotEmpty()
  destinationPublicKey: string;

  @ApiProperty({
    description: 'Settlement amount in USDC tokens (as a string to preserve precision)',
    example: '250.5000',
  })
  @IsNumberString()
  @IsNotEmpty()
  amount: string;

  @ApiPropertyOptional({
    description: 'Transaction memo for anchors. If omitted, auto-generated by MemoResolver based on destination anchor.',
    example: 'FW-a1b2c3d4',
  })
  @IsOptional()
  @IsString()
  memo?: string;
}
